import { build } from 'esbuild'
import { mkdir, readFile, writeFile, copyFile, readdir, rm } from 'node:fs/promises'
import { resolve, relative, sep, basename } from 'node:path'

import { createHash } from 'node:crypto'
import { ensureUpstream, upstreamRoot } from './upstream.mjs'

await ensureUpstream()
const componentCss = new Map()
const nativeComponents = {
  name: 'official-ui-components',
  setup(builder) {
    builder.onResolve({ filter: /^@deepseek-ai\/dsh-client-ui-primitives$/ }, () => ({ path: resolve('scripts/native-components.jsx') }))
    builder.onLoad({ filter: /\.module\.css$/ }, async ({ path }) => {
      const source = await readFile(path, 'utf8')
      const sourceId = relative(upstreamRoot, path).split(sep).join('/')
      const prefix = `dshjapanese_${createHash('sha256').update(sourceId).digest('hex').slice(0, 8)}_`
      const classes = Object.fromEntries([...source.matchAll(/\.([a-zA-Z_][\w-]*)/g)].map(match => [match[1], prefix + match[1]]))
      let css = source.replace(/:global\(([^)]+)\)/g, (_, selector) => selector.replaceAll('.', '__GLOBAL_DOT__'))
      css = css.replace(/\.([a-zA-Z_][\w-]*)/g, (_, name) => `.${classes[name]}`).replaceAll('__GLOBAL_DOT__', '.')
      componentCss.set(path, css)
      return { contents: `export default ${JSON.stringify(classes)}`, loader: 'js' }
    })
  },
}
await build({ entryPoints: ['scripts/native-components.jsx'], bundle: true, platform: 'browser', format: 'cjs', write: false, jsx: 'automatic', external: ['react', 'react/jsx-runtime', 'react-dom'], plugins: [nativeComponents] })
const cssEntries = [...componentCss].sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0)
await writeFile('.cache/native-controls.css', cssEntries.map(([, css]) => css).join('\n'))

await mkdir('.cache', { recursive: true })
await mkdir('dist', { recursive: true })
const fontRoot = resolve('node_modules/@fontsource-variable/noto-sans-jp')
const fontOut = resolve('dist/fonts')
await rm(fontOut, { recursive: true, force: true })
await mkdir(fontOut, { recursive: true })
let fontCss = await readFile(resolve(fontRoot, 'wght.css'), 'utf8')
const fontNames = new Set()
for (const match of [...fontCss.matchAll(/url\(([^)]+)\)/g)]) {
  const spec = match[1].replaceAll("'", '').replaceAll('"', '')
  const name = basename(spec)
  fontNames.add(name)
  await copyFile(resolve(fontRoot, spec), resolve(fontOut, name))
  fontCss = fontCss.replace(match[0], `url(/dsh-japanese/fonts/${name})`)
}
fontCss = fontCss.replaceAll('Noto Sans JP Variable', 'DSH Japanese UI')
await writeFile('.cache/font-css.mjs', `export default ${JSON.stringify(fontCss)};\n`)
await writeFile('src/font-files.mjs', `/** File names copied into dist/fonts. Regenerated by scripts/build.mjs. */\nexport const fontFileNames = ${JSON.stringify([...fontNames].sort(), null, 2)}\n`)
const translations = {}
for (const file of await readdir('translations')) {
  if (file.endsWith('.json') && file !== 'index.json') {
    translations[file.slice(0, -5)] = JSON.parse(await readFile(`translations/${file}`, 'utf8'))
  }
}
await writeFile('.cache/translations.json', JSON.stringify(translations))
const manifest = JSON.parse(await readFile('package.json', 'utf8'))
await build({ entryPoints: ['src/index.mjs'], outfile: 'dist/index.js', bundle: true, platform: 'node', format: 'esm', target: 'node22', external: ['@deepseek-ai/*'] })
const client = await build({ entryPoints: ['src/client.jsx'], bundle: true, platform: 'browser', format: 'cjs', target: 'es2022', write: false, jsx: 'automatic', external: ['react', 'react/jsx-runtime', 'react-dom'], plugins: [nativeComponents], loader: { '.css': 'text' }, minify: true })
await writeFile('dist/client.js', `window.__ModuleLoader__.load({id:${JSON.stringify(manifest.name)},factory(require){const module={exports:{}};const exports=module.exports;\n${client.outputFiles[0].text}\nreturn module.exports;}});\n`)
await copyFile(resolve(fontRoot, 'LICENSE'), 'dist/Noto-Sans-JP-OFL.txt')
console.log(`${manifest.name}: built`)
